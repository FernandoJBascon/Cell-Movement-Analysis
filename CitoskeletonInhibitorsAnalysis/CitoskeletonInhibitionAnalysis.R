## 2. Statistical analysis and plotting                                                                  ##
###########################################################################################################

## After having extracted the information needed, we combine all of it into a dataframe:

ControlSample <- c(rep("Control",9))
DMSOSample <- c(rep("DMSO",35))
CKSample <- c(rep("CK666",41))
LatSample <- c(rep("Latrunculin",27))
BlbSample <- c(rep("Blebbistatin",33))

Sample <- c(CKSample,BlbSample,LatSample,DMSOSample,ControlSample)
Norm_Speed <- c(CK666.norm.speed,Blebb.norm.speed,Lat.norm.speed,DMSO.norm.speed,Control.norm.speed)

InhibitorsData <- data.frame(Sample,Norm_Speed)

InhibitorsData$Sample <- factor(InhibitorsData$Sample, levels = c("Control","DMSO","Latrunculin","CK666","Blebbistatin"))

## After this, we proceed with the statistical analysis, checking first the normality of the data before deciding which
## statistical test will be used:

shapiro.test(Control.norm.speed) # p-value = 0.11
shapiro.test(DMSO.norm.speed) # p-value = 0.028
shapiro.test(CK666.norm.speed) # p-value = 0.028
shapiro.test(Lat.norm.speed) # p-value = 0.00018
shapiro.test(Blebb.norm.speed) # p-value = 0.00016

## As we can see, any of them except the control follow a normal distribution, so the appropiate statistical test is the 
## wilcoxon test:

wilcox.test(Control.norm.speed, DMSO.norm.speed, alternative = "greater") # p-value: 0.0003
wilcox.test(DMSO.norm.speed, Lat.norm.speed, alternative = "greater") # p-value: 0.03
wilcox.test(DMSO.norm.speed, CK666.norm.speed, alternative = "greater") # p-value: 1.75e-10
wilcox.test(DMSO.norm.speed, Blebb.norm.speed, alternative = "greater") # p-value: 7.443e-11

## We proceed with generating a violin plot:

ggplot(InhibitorsData, aes(x=Sample, y=Norm_Speed, fill=Sample)) +
  geom_violin() + 
  labs(title = "Normalized speed of medusa cells after different treatments", x="Treatment", y="Speed Normalized") +
  theme_light()  +
  theme(axis.title = element_blank()) +
  scale_fill_manual(values=c("#E6AF2E66","#9A031E99","#F4845F99","#F3A68D99","#F3665F99")) +
  theme(axis.title = element_text(face = "bold.italic", size = 11)) +
  theme(plot.title = element_text(face = "bold.italic", size = 13)) +
  theme(axis.text = element_text(face = "bold")) +
  geom_signif(data=InhibitorsData,comparisons=list(c("Control","DMSO")),map_signif_level = TRUE,annotations="***", y_position = 30) +
  geom_signif(data=InhibitorsData,comparisons=list(c("DMSO","Latrunculin")),map_signif_level = TRUE,annotations="*", y_position = 25) +
  geom_signif(data=InhibitorsData,comparisons=list(c("DMSO","CK666")),map_signif_level = TRUE,annotations="****", y_position = 27.5) +
  geom_signif(data=InhibitorsData,comparisons=list(c("DMSO","Blebbistatin")),map_signif_level = TRUE,annotations="****", y_position = 30) +
  theme(legend.position = "none")

