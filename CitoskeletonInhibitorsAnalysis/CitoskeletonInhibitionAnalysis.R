DMSOV3.ct.mean.speed <- as.numeric(Filter$TRACK_MEAN_SPEED)*2

## Finally we combine all the data, and normalize also taking into account the adjustment of speed, 
## with the difference that for all the videos except the controls above, the images were taken
## every 30 seconds:

DMSO.norm.speed <- c(DMSOV1.mc.mean.speed/mean(DMSOV1.ct.mean.speed),
                          DMSOV2.mc.mean.speed/mean(DMSOV2.ct.mean.speed),
                          DMSOV3.mc.mean.speed/mean(DMSOV3.ct.mean.speed))

mean(DMSO.norm.speed) ## 8.96µm/min

