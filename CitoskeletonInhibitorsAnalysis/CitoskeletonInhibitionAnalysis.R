## 1. Data preparation                                                                                   ##
###########################################################################################################

## The track data generated by TrackMate (2,3) has info about all cells present in the video, not only of Medusa
## cells, for this reason, before doing any analysis we selected the Medusaa cell tracks from each file, 
## extracted the mean speed of each of them and group them in one variable that will be used later for the 
## statistical analysis and plotting. 

## Each sample was composed by different videos, meaning, each sample has a set of various .csv files. All
## these .csv data files are located in the folder TrackData and classified by sample. For the controls, 
## only a subset of the Medusa cells used in the analysis were we characterized the movement before and
## after Head/Tail separation was used. The reason for this subset (Medusa cells 1 through 7, 9 and 14) was 
## TrackMate (2,3). The way this plugin works need the cells to not be grouped in big clumps nor too crowded.
## For this reason, we could not use this approach for all the Medusa cells analysed before, even though we
## could do it manually at the time. 

## Also, the different inhibitors were added while the video was been taken. This induced some media flow that 
## pushed all the cells present. To try to remove this artifact, we decided to track some controls 
## (coenocytes/uninuclear cells) from inside each video and normalize the speed data by dividing the Medusa 
## cells speed by the mean of all the control speeds.

##############
##  Control ##
##############

## Differently from the rest of the data files, untreated controls only have the Medusa cells/Coenocyte/Uninuclear cell
## data in the .csv files, so we do not need to manually extract the tracks corresponding to them. The Medusa cells 
## analysed where the same ones from the Before and After Head/Tail separation analysis. Not all of them were used, 
## only MC1-7, MC9 and MC14 where used. 

ControlMCData <- read.table("TrackData/Controls/MedusaTracks.csv", header=T, sep=",")
ControlCTData <- read.table("TrackData/Controls/ControlTracks.csv", header=T, sep=",")

## Since our video data did not have any metadata about the time between images, TrackMate (2,3) consider it to
## be 1 minute but the actual time was 90sec, so we need to adjust for that now so the speed is in µm/min.

Control.mc.mean.speed <- as.numeric(ControlMCData$TRACK_MEAN_SPEED)*6/9
Control.ct.mean.speed <- as.numeric(ControlCTData$TRACK_MEAN_SPEED)*6/9

## After that we calculate the normalization:

Control.norm.speed <- Control.mc.mean.speed/mean(Control.ct.mean.speed)

mean(Control.norm.speed) ## 15.42µm/min

