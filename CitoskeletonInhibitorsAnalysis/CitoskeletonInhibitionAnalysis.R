## - Latrunculin: Actin depolymerator (27 Medusa cells)
## - Blebbistatin: Myosin inhibitor (33 Medusa cells)

## The Medusa cells were filmed after the addition of each inhibitor. The videos were analysed using Fiji (1),
## this time, using TrackMate plugin (2,3). The control untreated Medusa cells used were the same ones as for the
## analysis before and after Head/Tail separation, that were re-analysed using TrackMate (2,3) for this experiment
## (more information about it down below). 

