## For this experiment, Medusa cells were treated with different inhibitors for different components of the
## cytoskeleton: 
## - Control: untreated Medusa cells (9 Medusa cells)
## - DMSO Control: Medusa cells treated in DMSO since the inhibitors are diluted in it (35 Medusa cells)
